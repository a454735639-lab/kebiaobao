    /// 农历月序列：(月号 1-12, 是否闰月, 天数)。每年结果固定，缓存避免重复构造数组。
    private static var monthSeqCache: [Int: [(month: Int, leap: Bool, days: Int)]] = [:]

    private static func months(of year: Int) -> [(month: Int, leap: Bool, days: Int)] {
        if let c = monthSeqCache[year] { return c }
        let code = yearCode[year - 1900]
        let leapMonth = code & 0xF          // 低 4 位 = 闰月月份，0 = 无闰
        let leapBig = (code >> 16) & 1      // 高 4 位最低位 = 闰月大小
        var out: [(Int, Bool, Int)] = []
        for i in 0..<12 {
            // 中 12 位 bit15..bit4 依次为 1..12 月大小
            let big = (code >> (15 - i)) & 1
            out.append((i + 1, false, big == 1 ? 30 : 29))
            if leapMonth != 0 && i + 1 == leapMonth {
                out.append((i + 1, true, leapBig == 1 ? 30 : 29))
            }
        }
        monthSeqCache[year] = out
        return out
    }

    /// 复用同一个 Calendar：原来每次调用都新建一个（月历一屏 42 次）
    private static let cal = Calendar(identifier: .gregorian)

    /// 公历 → 农历。返回 (月号, 日, 是否闰月, 月名, 日名)
    static func date(_ d: Date) -> (month: Int, day: Int, leap: Bool, monthName: String, dayName: String)? {
        let comps = cal.dateComponents([.year, .month, .day], from: d)
        guard let y = comps.year, let m = comps.month, let dd = comps.day else { return nil }
        return date(y, m, dd)
    }

    static func date(_ y: Int, _ m: Int, _ dd: Int) -> (month: Int, day: Int, leap: Bool, monthName: String, dayName: String)? {
        guard y >= 1900, y <= 2100 else { return nil }
        // 先定位农历年：若在当年正月初一之前，则属上一农历年
        var ly = y
        var offset = offsetFromNewYear(y, m, dd)
        if offset < 0 {
            ly = y - 1
            guard ly >= 1900 else { return nil }
            offset = offsetFromNewYear(ly, m, dd)
        }
        guard offset >= 0 else { return nil }

        var rest = offset
        for mo in months(of: ly) {
            if rest < mo.days {
                let nm = (mo.leap ? "闰" : "") + monthName[mo.month - 1]
                return (month: mo.month, day: rest + 1, leap: mo.leap,
                        monthName: nm, dayName: dayName[rest])
            }
            rest -= mo.days
        }
        return nil
    }

    /// 距该年正月初一的天数（负 = 还没到）
    private static func offsetFromNewYear(_ y: Int, _ m: Int, _ d: Int) -> Int {
        let base = newYearDay[y - 1900]
        return dayGap(y, m, d, base / 10000, (base / 100) % 100, base % 100)
    }

    /// 两个公历日相差天数
    private static func dayGap(_ y1: Int, _ m1: Int, _ d1: Int, _ y2: Int, _ m2: Int, _ d2: Int) -> Int {
        jdn(y1, m1, d1) - jdn(y2, m2, d2)
    }

    private static func jdn(_ y: Int, _ m: Int, _ d: Int) -> Int {
        var yy = y, mm = m
        if mm <= 2 { yy -= 1; mm += 12 }
        let a = yy / 100
        let b = 2 - a + a / 4
        return Int(365.25 * Double(yy + 4716)) + Int(30.6001 * Double(mm + 1)) + d + b - 1524
    }

    // MARK: - 节气

    /// 1900–2100 年逐年第 24 节气日。启动时一次性解析成扁平字节数组，
    /// 避免每次日期渲染都做 String 索引（原实现每个格子 O(n)）。
    private static let termDays: [UInt8] = {
        guard let url = Bundle.main.url(forResource: "solarterms", withExtension: "txt"),
              let s = try? String(contentsOf: url, encoding: .utf8)
        else { return [] }
        let digits = s.utf8.compactMap { $0 >= 48 && $0 <= 57 ? $0 - 48 : nil }
        guard digits.count % 2 == 0 else { return [] }
        var out = [UInt8](repeating: 0, count: digits.count / 2)
        for i in 0..<out.count { out[i] = digits[i * 2] * 10 + digits[i * 2 + 1] }
        return out
    }()

    /// 当天节气名（无则 nil）
    static func term(_ date: Date) -> String? {
        let comps = cal.dateComponents([.year, .month, .day], from: date)
        guard let y = comps.year, let m = comps.month, let d = comps.day else { return nil }
        guard y >= 1900, y <= 2100 else { return nil }
        let start = (y - 1900) * 24
        guard termDays.count >= start + 24 else { return nil }
        // 每个月的两个节气紧邻：k = (m-1)*2, (m-1)*2+1
        for k in [(m - 1) * 2, (m - 1) * 2 + 1] {
            if Int(termDays[start + k]) == d { return termName[k] }
        }
        return nil
    }
